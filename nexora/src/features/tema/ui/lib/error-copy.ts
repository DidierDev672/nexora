export function paletteListLoadError(): string {
  return 'Las paletas se tomaron un respiro y no quisieron salir esta vez. Nada se perdió: revisa tu conexión y reintenta cuando quieras; a veces el primer intento es solo el ensayo.'
}

export function paletteEmptyMessage(): string {
  return 'Todavía no hay paletas definidas. Cuando el sistema tenga colores listos, aparecerán aquí para que elijas con calma el estilo de tu Nexora.'
}